    module_function

    # Signed weight of a word, or nil when the word is not in the lexicon.
    #
    # @param word [String] any word (case-insensitive)
    # @return [Float, nil] positive or negative weight
    def lookup(word)
      key = word.to_s.downcase
      return POSITIVE[key] if POSITIVE.key?(key)
      return NEGATIVE[key] if NEGATIVE.key?(key)

      nil
    end

    # @param word [String] any word
    # @return [Boolean] true when the word carries positive polarity
    def positive?(word)
      POSITIVE.key?(word.to_s.downcase)
    end

    # @param word [String] any word
    # @return [Boolean] true when the word carries negative polarity
    def negative?(word)
      NEGATIVE.key?(word.to_s.downcase)
    end

    # @param word [String] any word
    # @return [Boolean] true when the word is a negator
    def negator?(word)
      NEGATOR_SET.include?(word.to_s.downcase)
    end

    # Modifier factor for intensifiers and diminishers.
    #
    # @param word [String] any word
    # @return [Float, nil] multiplicative factor, or nil when not a modifier
    def modifier(word)
      MODIFIERS[word.to_s.downcase]
    end

    # @return [Integer] total number of scored words in the lexicon
    def size
      POSITIVE.size + NEGATIVE.size
    end

    # @return [Boolean] true when the positive and negative tables share a key
    def conflicting_entries?
      !(POSITIVE.keys & NEGATIVE.keys).empty?
    end
